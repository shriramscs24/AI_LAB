import random
import math

N = 8

def count_conflicts(board):
    conflicts = 0
    for i in range(N):
        for j in range(i + 1, N):
            if board[i] == board[j] or abs(board[i] - board[j]) == abs(i - j):
                conflicts += 1
    return conflicts

def simulated_annealing():
    board = [random.randint(0, N - 1) for _ in range(N)]
    current_conflicts = count_conflicts(board)

    temp = 1000.0
    cooling_rate = 0.995

    while current_conflicts > 0 and temp > 0.001:
        row = random.randint(0, N - 1)
        new_col = random.randint(0, N - 1)

        if new_col != board[row]:
            original_col = board[row]
            board[row] = new_col
            neighbor_conflicts = count_conflicts(board)

            delta = neighbor_conflicts - current_conflicts

            if delta < 0 or random.random() < math.exp(-delta / temp):
                current_conflicts = neighbor_conflicts
            else:
                board[row] = original_col

        temp *= cooling_rate

    return board if current_conflicts == 0 else None

solution = None
while solution is None:
    solution = simulated_annealing()

print(solution)

for row in range(N):
    print(" ".join("Q" if solution[row] == col else "." for col in range(N)))
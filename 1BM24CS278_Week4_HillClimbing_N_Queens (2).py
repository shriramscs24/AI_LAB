import random

N = 4

def count_conflicts(board):
    conflicts = 0
    for i in range(N):
        for j in range(i + 1, N):
            if board[i] == board[j] or abs(board[i] - board[j]) == abs(i - j):
                conflicts += 1
    return conflicts

def get_best_neighbor(board):
    best_board = list(board)
    best_conflicts = count_conflicts(board)

    for row in range(N):
        original_col = board[row]
        for col in range(N):
            if col != original_col:
                board[row] = col
                neighbor_conflicts = count_conflicts(board)
                if neighbor_conflicts < best_conflicts:
                    best_conflicts = neighbor_conflicts
                    best_board = list(board)
                board[row] = original_col

    return best_board, best_conflicts

def hill_climbing():
    while True:
        current_board = [random.randint(0, N - 1) for _ in range(N)]
        current_conflicts = count_conflicts(current_board)

        while True:
            if current_conflicts == 0:
                return current_board

            neighbor_board, neighbor_conflicts = get_best_neighbor(current_board)

            if neighbor_conflicts >= current_conflicts:
                break

            current_board = neighbor_board
            current_conflicts = neighbor_conflicts

solution = hill_climbing()
print(solution)

for row in range(N):
    print(" ".join("Q" if solution[row] == col else "." for col in range(N)))